/* Define to prevent recursive inclusion ------------------------------------ */
#ifndef _BSP_WS2812_H
#define _BSP_WS2812_H

/* Includes ----------------------------------------------------------------- */
#include <stdint.h>

/* Defines ------------------------------------------------------------------ */

/* Enums -------------------------------------------------------------------- */
/**
 * @brief WS2812发送结果
 */
typedef enum
{
    BSP_WS2812_STATUS_OK = 0,
    BSP_WS2812_STATUS_CONFIG_ERROR,
    BSP_WS2812_STATUS_BUSY,
    BSP_WS2812_STATUS_TIMEOUT,
    BSP_WS2812_STATUS_ERROR
} BspWs2812Status_e;

/* Structs ------------------------------------------------------------------ */

/* Externs ------------------------------------------------------------------ */

/* Functions ---------------------------------------------------------------- */
/**
 * @brief  设置板载WS2812B颜色
 * @param  red: 红色亮度，范围0~255
 * @param  green: 绿色亮度，范围0~255
 * @param  blue: 蓝色亮度，范围0~255
 * @return WS2812发送结果
 * @note   本函数采用阻塞式SPI发送，正确配置下单次占用总线约93 us；
 *         驱动按WS2812要求转换为GRB线序，并在帧尾产生复位低电平。
 */
BspWs2812Status_e BSP_WS2812_SetColor(uint8_t red, uint8_t green, uint8_t blue);

/* -------------------------------------------------------------------------- */
#endif /* _BSP_WS2812_H */
